using System.Collections.Generic;

namespace HospitalDisplay.Api.Helpers
{
    /// <summary>
    /// Standard envelope for every API response so the frontend can rely on a
    /// consistent shape regardless of the endpoint.
    /// </summary>
    /// <typeparam name="T">Type of the payload returned on success.</typeparam>
    public class ApiResponse<T>
    {
        public bool Success { get; set; }
        public string Message { get; set; } = string.Empty;
        public T? Data { get; set; }
        public List<string>? Errors { get; set; }

        public static ApiResponse<T> SuccessResponse(T data, string message = "Request completed successfully")
        {
            return new ApiResponse<T>
            {
                Success = true,
                Message = message,
                Data = data,
                Errors = null
            };
        }

        public static ApiResponse<T> FailureResponse(string message, List<string>? errors = null)
        {
            return new ApiResponse<T>
            {
                Success = false,
                Message = message,
                Data = default,
                Errors = errors
            };
        }
    }
}
